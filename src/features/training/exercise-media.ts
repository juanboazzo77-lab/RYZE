const BY_LOWER = new Map(Object.entries(EXERCISE_MEDIA).map(([n, id]) => [n.toLowerCase(), id]));

/** Las dos fotos de la demostración, o null si el ejercicio no tiene. */
export function exerciseMedia(name: string): [string, string] | null {
  const id = BY_LOWER.get(name.trim().toLowerCase());
  return id ? [`${BASE}/${id}/0.jpg`, `${BASE}/${id}/1.jpg`] : null;
}
