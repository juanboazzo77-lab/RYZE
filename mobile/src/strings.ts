export const APP_TEXT: Record<Locale, AppText> = { es, en, pt, fr, de, it };

/** El idioma del teléfono, para antes de saber el de la cuenta. */
export const deviceLocale = (): Locale => normalizeLocale(navigator.language?.slice(0, 2).toLowerCase());

let current: Locale = deviceLocale();
const listeners = new Set<() => void>();

/** Al saber el idioma de la cuenta (o al cambiarlo en ajustes). */
export function setAppLocale(locale: Locale) {
  if (locale === current) return;
  current = locale;
  listeners.forEach((l) => l());
}

const subscribe = (listener: () => void) => {
  listeners.add(listener);
  return () => void listeners.delete(listener);
};

/** Para el código que no es una pantalla. */
export const currentAppLocale = () => current;

export const useAppLocale = () => useSyncExternalStore(subscribe, () => current);
export const useText = () => APP_TEXT[useAppLocale()];
